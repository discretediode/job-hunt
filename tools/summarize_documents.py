#!/usr/bin/env python3
"""Extract whatever is machine-readable from documents/ into one file for the agent.

  python3 tools/summarize_documents.py            -> documents/EXTRACT.md
  python3 tools/summarize_documents.py --selftest

documents/ holds the real paper: diplomas, language certificates, Arbeitszeugnisse,
transcripts, externally-authored CVs. The profile vault stays the source of truth for
CV content; these are the *evidence* behind it, and a reference letter's actual wording
is worth more in a cover letter than a paraphrase from memory.

Two-stage on purpose, same shape as to_judge.md -> ranked.json:

  this script  ->  documents/EXTRACT.md   mechanical, regenerable, ugly
  the agent    ->  documents/EVIDENCE.md   what each document PROVES, in one place

ponytail: pypdf only, no OCR dependency. A scanned certificate has no text layer, so
instead of installing tesseract this lists the file under NEEDS VISION and the agent
reads the image itself - it already can. Both outputs are gitignored: a transcript and
a reference letter are more personal than anything else in the repo.
"""
import pathlib
import sys

from pypdf import PdfReader

HERE = pathlib.Path(__file__).resolve().parent.parent
DOCS = HERE / "documents"
OUT = DOCS / "EXTRACT.md"

TEXT_SUFFIXES = {".md", ".txt", ".csv"}
IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png", ".heic", ".webp", ".tif", ".tiff"}
SKIP_NAMES = {".DS_Store", ".gitkeep", "README.md", "EXTRACT.md", "EVIDENCE.md"}

# Below this, a PDF's text layer is a scan rather than real text.
MIN_TEXT = 200
# A transcript can run long; the agent needs the gist, not every module row.
CAP = 4000


def pdf_text(path):
    """Extracted text, or '' when the PDF is a scan with no usable text layer."""
    try:
        r = PdfReader(path)
        return "\n".join((p.extract_text() or "") for p in r.pages).strip()
    except Exception as e:                       # a corrupt file must not stop the rest
        return f"__ERROR__ {type(e).__name__}: {e}"


def collect():
    """Return (readable, needs_vision, errors) for everything under documents/."""
    readable, needs_vision, errors = [], [], []
    for f in sorted(p for p in DOCS.rglob("*") if p.is_file()):
        if f.name in SKIP_NAMES:
            continue
        rel = f.relative_to(DOCS)
        suffix = f.suffix.lower()
        if suffix == ".pdf":
            t = pdf_text(f)
            if t.startswith("__ERROR__"):
                errors.append((rel, t.removeprefix("__ERROR__ ")))
            elif len(t) >= MIN_TEXT:
                readable.append((rel, t))
            else:
                needs_vision.append((rel, f"PDF with {len(t)} chars of text - a scan"))
        elif suffix in TEXT_SUFFIXES:
            readable.append((rel, f.read_text(encoding="utf-8", errors="replace").strip()))
        elif suffix in IMAGE_SUFFIXES:
            needs_vision.append((rel, f"image, {f.stat().st_size // 1024} KB"))
        else:
            needs_vision.append((rel, f"unrecognised type {suffix or '(none)'}"))
    return readable, needs_vision, errors


def main():
    if not DOCS.exists():
        sys.exit(f"no {DOCS.name}/ directory - nothing to summarise")
    readable, needs_vision, errors = collect()

    out = ["# documents/ - machine extract",
           "",
           "Generated by `tools/summarize_documents.py`. Regenerable, never hand-edited.",
           "",
           f"{len(readable)} readable, {len(needs_vision)} needing vision, "
           f"{len(errors)} unreadable.",
           "",
           "**Next step:** read the NEEDS VISION files below directly, then write",
           "`documents/EVIDENCE.md` - one short entry per document saying what it *proves*",
           "(grade, dates, employer, duties, the quotable line). That summary is what the",
           "letter-writing step consults; this file is just the raw pull.",
           ""]

    if needs_vision:
        out += ["", "## NEEDS VISION", ""]
        out += [f"- `{rel}` - {why}" for rel, why in needs_vision]

    if errors:
        out += ["", "## UNREADABLE", ""]
        out += [f"- `{rel}` - {why}" for rel, why in errors]

    out += ["", "## Extracted text", ""]
    for rel, t in readable:
        clipped = t[:CAP]
        out += [f"", f"### `{rel}`", ""]
        if len(t) > CAP:
            clipped += f"\n\n[... clipped, {len(t) - CAP} more chars]"
        out += ["```", clipped, "```"]

    OUT.write_text("\n".join(out) + "\n")
    for rel, _ in readable:
        print(f"  read    {rel}")
    for rel, why in needs_vision:
        print(f"  VISION  {rel}  ({why})")
    for rel, why in errors:
        print(f"  ERROR   {rel}  ({why})")
    print(f"\nwrote {OUT.relative_to(HERE)} ({OUT.stat().st_size // 1024} KB)")


def _selftest():
    """ponytail: the triage must route a text PDF, a scan and an image differently."""
    assert ".pdf" not in TEXT_SUFFIXES and ".pdf" not in IMAGE_SUFFIXES
    assert ".jpg" in IMAGE_SUFFIXES and ".md" in TEXT_SUFFIXES
    assert "EVIDENCE.md" in SKIP_NAMES, "the agent's own output must never be re-ingested"
    assert "EXTRACT.md" in SKIP_NAMES, "this script's output must never be re-ingested"
    assert MIN_TEXT > 0 and CAP > MIN_TEXT
    # A scan-like PDF (few chars) routes to vision, a real one to readable.
    for n, expect in ((0, "vision"), (MIN_TEXT - 1, "vision"), (MIN_TEXT, "readable")):
        assert ("readable" if n >= MIN_TEXT else "vision") == expect, n
    print("selftest ok")


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "--selftest":
        _selftest()
    else:
        main()
